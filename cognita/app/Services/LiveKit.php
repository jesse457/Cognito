<?php

declare(strict_types=1);

namespace App\Services;

use App\Models\Classroom;
use App\Models\User;
use Illuminate\Http\Client\PendingRequest;
use Illuminate\Http\Client\Response;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Http;
use RuntimeException;
use Throwable;

/**
 * LiveKit access tokens, addressing and health checks.
 *
 * The server is configured under services.livekit. Tokens are signed locally
 * (a plain HS256 JWT) so the PHP app needs no LiveKit SDK: the grant is limited
 * to one room and a short TTL. Only the instructor starts with permission to
 * publish a microphone; a student's publish permission is opened for one call
 * at a time through the room service API.
 *
 * The one rule worth remembering is how the browser addresses the call server.
 * By default the host is taken from the request itself, so a phone that loads
 * the app at http://192.168.1.20:8000 dials ws://192.168.1.20:7880, a laptop on
 * localhost dials ws://localhost:7880, and an HTTPS page dials wss:// on its own
 * port. Nothing about the network has to be written into .env, which is what
 * lets the same checkout work on this machine, on a phone on the same Wi-Fi and
 * behind a tunnel without editing anything.
 */
class LiveKit
{
    /** Sessions are opaque, short, and generated by the client per tab. */
    public const SESSION_PATTERN = '/^[a-z0-9]{6,16}$/';

    /** Room name used by the health check; never a real class. */
    private const PROBE_ROOM = 'cognita-health-check';

    /**
     * What a permitted participant may publish. Camera is deliberately absent:
     * a class shares microphones and screens, not webcam feeds.
     */
    private const PUBLISH_SOURCES = ['microphone', 'screen_share', 'screen_share_audio'];

    /** The same grants as LiveKit's RoomService JSON enum names. */
    private const PUBLISH_SOURCES_RPC = ['MICROPHONE', 'SCREEN_SHARE', 'SCREEN_SHARE_AUDIO'];

    public function configured(): bool
    {
        $keys = filled(config('services.livekit.api_key'))
            && filled(config('services.livekit.api_secret'));

        return $keys && ($this->followsRequest() || filled(config('services.livekit.url')));
    }

    public function assertConfigured(): void
    {
        abort_unless($this->configured(), 503, 'Live calls are not configured on this server.');
    }

    /** Whether the browser address is derived from the request. */
    public function followsRequest(): bool
    {
        return strtolower((string) config('services.livekit.url_mode', 'auto')) !== 'fixed';
    }

    /**
     * The address this browser must dial.
     *
     * Pass the current request whenever one exists; without it (console, queue
     * worker) the configured URL or the loopback address is used.
     */
    public function signalUrl(?Request $request = null): string
    {
        $fixed = trim((string) config('services.livekit.url'));

        if (! $this->followsRequest() || $request === null) {
            return $fixed !== '' ? $fixed : $this->loopbackUrl();
        }

        $secure = $request->isSecure();
        $port = $secure ? $this->securePort($request) : (int) config('services.livekit.port', 7880);

        return ($secure ? 'wss' : 'ws').'://'.$this->hostAndPort($request->getHost(), $port);
    }

    /**
     * A page served over plain HTTP on a LAN address cannot use the microphone:
     * browsers only expose it on a secure origin. When a TLS front is running we
     * can tell the visitor exactly where to go instead.
     */
    public function secureUrl(Request $request, ?string $path = null): ?string
    {
        $port = (int) config('services.livekit.tls_port', 0);

        if ($port < 1 || $request->isSecure()) {
            return null;
        }

        return 'https://'.$this->hostAndPort($request->getHost(), $port).($path ?? $request->getRequestUri());
    }

    /**
     * @return array{url: string, token: string, room: string, identity: string, role: string, expires_at: string}
     */
    public function token(
        User $user,
        Classroom $classroom,
        string $role,
        ?string $session = null,
        ?Request $request = null,
    ): array {
        $this->assertConfigured();

        $ttl = max(60, min((int) config('services.livekit.token_ttl', 3600), 21600));
        $now = now();
        $room = $classroom->roomName();
        // One LiveKit participant per browser tab: a shared identity would make
        // the server kick the older session every time a second tab or device
        // joins the same call.
        $identity = 'user-'.$user->getKey();

        if (is_string($session) && preg_match(self::SESSION_PATTERN, $session) === 1) {
            $identity .= '-'.$session;
        }

        $canPublish = $role === ClassroomAccess::ROLE_HOST;

        $token = $this->encode([
            'iss' => (string) config('services.livekit.api_key'),
            'sub' => $identity,
            'name' => $user->name,
            'nbf' => $now->getTimestamp(),
            'exp' => $now->copy()->addSeconds($ttl)->getTimestamp(),
            'video' => [
                'roomJoin' => true,
                'room' => $room,
                'canPublish' => $canPublish,
                'canSubscribe' => true,
                'canPublishData' => true,
                'canPublishSources' => self::PUBLISH_SOURCES,
                'roomAdmin' => $role === ClassroomAccess::ROLE_HOST,
                'hidden' => false,
                'recorder' => false,
            ],
            'metadata' => json_encode([
                'role' => $role,
                'classroom_id' => (int) $classroom->getKey(),
                'classroom_name' => $classroom->name,
            ], JSON_THROW_ON_ERROR),
        ]);

        return [
            'url' => $this->signalUrl($request),
            'token' => $token,
            'room' => $room,
            'identity' => $identity,
            'role' => $role,
            'expires_at' => $now->copy()->addSeconds($ttl)->toIso8601String(),
        ];
    }

    /**
     * Remove one participant session from a room using LiveKit's server API.
     * The grant is room-scoped and short-lived; the browser never sees it.
     */
    public function removeParticipant(Classroom $classroom, string $identity, ?Request $request = null): void
    {
        $this->assertConfigured();

        $controlUrl = $this->controlUrl($this->signalUrl($request));

        $response = $this->roomAdminClient($controlUrl, $classroom, 'cognita-moderation')
            ->post($controlUrl.'/twirp/livekit.RoomService/RemoveParticipant', [
                'room' => $classroom->roomName(),
                'identity' => $identity,
            ]);

        if (! $response->successful()) {
            throw new RuntimeException('LiveKit could not remove that participant (HTTP '.$response->status().').');
        }
    }

    /**
     * Close the call server's room, which disconnects every participant.
     *
     * A room that has already emptied itself is not an error: the class session
     * is already closed in the database, and there is nothing left to drop.
     */
    public function endRoom(Classroom $classroom, ?Request $request = null): void
    {
        $this->assertConfigured();

        $controlUrl = $this->controlUrl($this->signalUrl($request));

        $response = $this->roomAdminClient($controlUrl, $classroom, 'cognita-end-class', roomCreate: true)
            ->post($controlUrl.'/twirp/livekit.RoomService/DeleteRoom', [
                'room' => $classroom->roomName(),
            ]);

        if ($response->successful() || $response->status() === 404) {
            return;
        }

        throw new RuntimeException('LiveKit could not close the class room (HTTP '.$response->status().').');
    }

    /**
     * Open or close one participant's microphone through the room service API.
     *
     * LiveKit keeps this only on the live participant; revoking canPublish also
     * unpublishes anything they already sent, so the next join needs a fresh
     * instructor approval. Nothing about the approval touches the database.
     */
    public function setMicrophonePermission(
        Classroom $classroom,
        string $identity,
        bool $allowed,
        ?Request $request = null,
    ): void {
        $this->assertConfigured();

        $controlUrl = $this->controlUrl($this->signalUrl($request));

        $response = $this->roomAdminClient($controlUrl, $classroom, 'cognita-permissions')
            ->post($controlUrl.'/twirp/livekit.RoomService/UpdateParticipant', [
                'room' => $classroom->roomName(),
                'identity' => $identity,
                'permission' => [
                    'canSubscribe' => true,
                    'canPublish' => $allowed,
                    'canPublishData' => true,
                    'canPublishSources' => self::PUBLISH_SOURCES_RPC,
                    'hidden' => false,
                    'recorder' => false,
                ],
            ]);

        if (! $response->successful()) {
            throw new RuntimeException('LiveKit could not update that microphone permission (HTTP '.$response->status().').');
        }
    }

    /**
     * Everything the call page and the livekit:check command need in order to
     * say why a call cannot work, in the order that matters:
     *
     *   1. configuration - is there a key and a secret at all?
     *   2. signal        - does the address the browser dials answer HTTP?
     *   3. credentials   - does LiveKit accept tokens signed with our secret?
     *   4. media         - does a UDP datagram reach LiveKit and come back?
     *
     * @return array{url: string, secure_url: string|null, checks: list<array{key: string, label: string, ok: bool, detail: string}>}
     */
    public function diagnose(?Request $request = null, ?string $pagePath = null): array
    {
        $url = $this->signalUrl($request);
        $controlUrl = $this->controlUrl($url);
        $host = (string) parse_url($url, PHP_URL_HOST);

        return [
            'url' => $url,
            // The health endpoint reports the page a visitor should open, not
            // the health endpoint itself.
            'secure_url' => $request === null ? null : $this->secureUrl($request, $pagePath),
            'checks' => [
                $this->checkConfiguration(),
                $this->checkSignal($controlUrl),
                $this->checkCredentials($controlUrl),
                $this->checkMedia($host, $url),
            ],
        ];
    }

    // ------------------------------------------------------------------ checks

    /** @return array{key: string, label: string, ok: bool, detail: string} */
    private function checkConfiguration(): array
    {
        $key = (string) config('services.livekit.api_key');
        $secret = (string) config('services.livekit.api_secret');

        if ($key === '' || $secret === '') {
            return $this->check('configuration', 'Configuration', false, 'LIVEKIT_API_KEY and LIVEKIT_API_SECRET must both be set.');
        }

        return $this->check(
            'configuration',
            'Configuration',
            true,
            $this->followsRequest()
                ? 'keys loaded; the address follows whoever opens the page'
                : 'keys loaded; the address is pinned to '.(string) config('services.livekit.url'),
        );
    }

    /**
     * Asks the signalling address a question only LiveKit can answer. The TLS
     * front also serves the app, so a plain GET / would be the Laravel page and
     * would call a broken route healthy; /rtc/validate rejects a junk token with
     * 401, which proves the path really lands on LiveKit.
     *
     * @return array{key: string, label: string, ok: bool, detail: string}
     */
    private function checkSignal(string $controlUrl): array
    {
        try {
            $response = $this->head($controlUrl.'/rtc/validate?access_token=not-a-token');

            if (in_array($response->status(), [200, 401, 403], true)) {
                return $this->check('signal', 'Signal connection', true, $controlUrl.' is answering as LiveKit (HTTP '.$response->status().' to a rejected token).');
            }

            return $this->check('signal', 'Signal connection', false, $controlUrl.' answered HTTP '.$response->status().', which is not a LiveKit reply. Check that TCP 7880 (or the HTTPS front) is routed to LiveKit.');
        } catch (Throwable $error) {
            return $this->check('signal', 'Signal connection', false, 'Could not reach '.$controlUrl.' ('.$this->reason($error).'). Start LiveKit and make sure TCP 7880 reaches it.');
        }
    }

    /** @return array{key: string, label: string, ok: bool, detail: string} */
    private function checkCredentials(string $controlUrl): array
    {
        $token = $this->encode([
            'iss' => (string) config('services.livekit.api_key'),
            'sub' => 'cognita-health-check',
            'nbf' => now()->subMinute()->getTimestamp(),
            'exp' => now()->addMinute()->getTimestamp(),
            'video' => [
                'roomJoin' => true,
                'room' => self::PROBE_ROOM,
                'canPublish' => false,
                'canSubscribe' => false,
            ],
        ]);

        try {
            $response = $this->head($controlUrl.'/rtc/validate?access_token='.urlencode($token));

            return $response->successful()
                ? $this->check('credentials', 'API key and secret', true, 'LiveKit accepted a token signed with LIVEKIT_API_SECRET.')
                : $this->check('credentials', 'API key and secret', false, 'LiveKit rejected our token (HTTP '.$response->status().'). LIVEKIT_API_KEY / LIVEKIT_API_SECRET do not match the server keys.');
        } catch (Throwable $error) {
            return $this->check('credentials', 'API key and secret', false, 'Could not ask LiveKit to validate a token ('.$this->reason($error).').');
        }
    }

    /**
     * A real UDP round trip. LiveKit's TURN listener answers an unauthenticated
     * STUN binding request, which answers the question a WebSocket cannot: does
     * a datagram survive the trip to the media port and back?
     *
     * @return array{key: string, label: string, ok: bool, detail: string}
     */
    private function checkMedia(string $host, string $url): array
    {
        if ($host === '') {
            return $this->check('media', 'Media (UDP)', false, 'Could not work out the call server host from '.$url.'.');
        }

        $port = (int) config('services.livekit.turn_port', 3478);
        $address = $host.':'.$port;

        try {
            $reply = $this->stun('udp://'.$address);

            if ($reply === null) {
                return $this->check('media', 'Media (UDP)', false, 'No STUN reply from '.$address.' within two seconds: UDP '.$port.' does not reach the call server. Open it in the host firewall and start LiveKit with TURN enabled; on mobile data the carrier often blocks it, so use Wi-Fi.');
            }

            return $this->check('media', 'Media (UDP)', true, 'STUN reply from '.$reply.' - UDP media reaches the call server and comes back.');
        } catch (Throwable $error) {
            return $this->check('media', 'Media (UDP)', false, 'Could not probe '.$address.' ('.$this->reason($error).').');
        }
    }

    // ----------------------------------------------------------------- helpers

    /**
     * A short-lived room-admin client for the RoomService API. The browser
     * never sees this token; it only carries the room this one action needs.
     * Deleting a room is gated by LiveKit's roomCreate grant, not roomAdmin.
     */
    private function roomAdminClient(
        string $controlUrl,
        Classroom $classroom,
        string $subject,
        bool $roomCreate = false,
    ): PendingRequest {
        $now = now();
        $token = $this->encode([
            'iss' => (string) config('services.livekit.api_key'),
            'sub' => $subject,
            'nbf' => $now->getTimestamp(),
            'exp' => $now->copy()->addMinutes(2)->getTimestamp(),
            'video' => [
                'roomAdmin' => true,
                'roomCreate' => $roomCreate,
                'room' => $classroom->roomName(),
            ],
        ]);

        $client = Http::timeout(10)
            ->acceptJson()
            ->withToken($token);

        // A local TLS front uses a self-signed certificate; this is a server
        // action against our own call server, not a public request.
        if (str_starts_with($controlUrl, 'https://')) {
            $client = $client->withoutVerifying();
        }

        return $client;
    }

    /** @return array{key: string, label: string, ok: bool, detail: string} */
    private function check(string $key, string $label, bool $ok, string $detail): array
    {
        return ['key' => $key, 'label' => $label, 'ok' => $ok, 'detail' => $detail];
    }

    /** LiveKit's control API speaks HTTP where the browser speaks WebSocket. */
    private function controlUrl(string $signalUrl): string
    {
        return preg_replace('/^ws/', 'http', rtrim($signalUrl, '/')) ?? $signalUrl;
    }

    /**
     * Sends the smallest valid STUN binding request and waits briefly for the
     * success reply. Returns the address that answered, or null on silence.
     */
    private function stun(string $uri): ?string
    {
        $socket = @stream_socket_client($uri, $errno, $error, 2);

        if ($socket === false) {
            throw new RuntimeException(is_string($error) && $error !== '' ? $error : 'the socket could not be opened');
        }

        try {
            stream_set_timeout($socket, 2);

            $request = pack('nnN', 0x0001, 0x0000, 0x2112A442).random_bytes(12);

            fwrite($socket, $request);

            $reply = fread($socket, 256);

            if (! is_string($reply) || strlen($reply) < 20) {
                return null;
            }

            if (unpack('n', $reply)[1] !== 0x0101) {
                return null;
            }

            $peer = stream_socket_get_name($socket, true);

            return is_string($peer) && $peer !== '' ? $peer : $uri;
        } finally {
            fclose($socket);
        }
    }

    private function head(string $url): Response
    {
        $request = Http::timeout(4)->acceptJson();

        // A local TLS front uses a self-signed certificate; this check is about
        // reachability, not about chain trust.
        if (str_starts_with($url, 'https://')) {
            $request = $request->withoutVerifying();
        }

        return $request->get($url);
    }

    private function reason(Throwable $error): string
    {
        $message = trim($error->getMessage());

        return $message === '' ? $error::class : $message;
    }

    private function loopbackUrl(): string
    {
        return 'ws://127.0.0.1:'.(int) config('services.livekit.port', 7880);
    }

    private function securePort(Request $request): ?int
    {
        $override = (int) config('services.livekit.secure_port', 0);

        return $override > 0 ? $override : $request->getPort();
    }

    private function hostAndPort(string $host, ?int $port): string
    {
        $host = trim($host, '[]');

        if ($port === null || $port === 80 || $port === 443) {
            return $host;
        }

        return $host.':'.$port;
    }

    /**
     * @param  array<string, mixed>  $payload
     */
    private function encode(array $payload): string
    {
        $header = $this->base64Url(json_encode(['alg' => 'HS256', 'typ' => 'JWT'], JSON_THROW_ON_ERROR));
        $body = $this->base64Url(json_encode($payload, JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR));
        $signature = hash_hmac(
            'sha256',
            $header.'.'.$body,
            (string) config('services.livekit.api_secret'),
            true,
        );

        return $header.'.'.$body.'.'.$this->base64Url($signature);
    }

    private function base64Url(string $value): string
    {
        return rtrim(strtr(base64_encode($value), '+/', '-_'), '=');
    }
}
